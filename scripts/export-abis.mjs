// Generates the files that tie the API and the web app to the deployed contracts:
//   src/onchain/generated/{PaytagRegistry,PaytagResolver}Abi.ts   from the Foundry build (contracts/out)
//   src/onchain/generated/reservedNodes.ts                       from PaytagRegistry.isReserved
//   src/onchain/generated/endpoints.ts                           the public RPC, from web/lib/endpoints.json
//   web/lib/onchain/generated/*                                  copies of the ABIs and the reserved list,
//                                                                plus the deployment constants, the ENSIP-9
//                                                                codec and name normalization (src/onchain/)
//
//   npm run abis         write the files
//   npm run abis:check   exit 1 if any committed file is stale
// Run `forge build` in contracts/ first. The ABI is frozen at tag v0.2.0-contracts, so --check
// failing in CI means something changed without the generated copies being regenerated.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256, stringToBytes } from "viem";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const onchain = join(repo, "src", "onchain");
const apiGenerated = join(onchain, "generated");
const webGenerated = join(repo, "web", "lib", "onchain", "generated");
const check = process.argv.includes("--check");

let stale = false;

/** Write `source` to `target`, or with --check, report whether the committed file differs. */
function emit(target, source) {
  const rel = relative(repo, target).replace(/\\/g, "/");
  if (check) {
    const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== source) {
      console.error(`stale: ${rel} (run \`npm run abis\`)`);
      stale = true;
    }
    return;
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, source);
  console.log(`wrote ${rel}`);
}

const header = (from) => `// Generated by scripts/export-abis.mjs from ${from}. Do not edit.\n`;

// ABIs.
for (const name of ["PaytagRegistry", "PaytagResolver"]) {
  const artifact = join(repo, "contracts", "out", `${name}.sol`, `${name}.json`);
  if (!existsSync(artifact)) {
    console.error(`missing ${artifact}; run \`forge build\` in contracts/ first`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
  const source =
    header(`contracts/out/${name}.sol`) + `export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  emit(join(apiGenerated, `${name}Abi.ts`), source);
  emit(join(webGenerated, `${name}Abi.ts`), source);
}

// Reserved list: a pure function baked into the immutable registry, so it's answered locally
// instead of with an RPC call per request.
{
  const sol = readFileSync(join(repo, "contracts", "src", "PaytagRegistry.sol"), "utf8");
  const entries = [...sol.matchAll(/node == (0x[0-9a-fA-F]{64})\s*\/\/\s*([a-z0-9_]+)/g)].map((m) => [
    m[2],
    m[1].toLowerCase(),
  ]);
  // Every hash in the contract must be extracted (none silently dropped for a missing or
  // malformed `// name` comment), and every comment must name the string that hashes to it.
  const allHashes = sol.match(/node == 0x[0-9a-fA-F]{64}/g) ?? [];
  if (entries.length === 0 || entries.length !== allHashes.length) {
    console.error(
      `reserved list: extracted ${entries.length} of ${allHashes.length} hashes; ` +
        "every `node == 0x…` in isReserved needs a trailing `// name` comment",
    );
    process.exit(1);
  }
  for (const [name, hash] of entries) {
    if (keccak256(stringToBytes(name)) !== hash) {
      console.error(`reserved list: comment "${name}" does not match hash ${hash}`);
      process.exit(1);
    }
  }
  const source =
    header("PaytagRegistry.isReserved") +
    `export const RESERVED_NODES: ReadonlySet<string> = new Set([\n` +
    entries.map(([name, hash]) => `  "${hash}", // ${name}\n`).join("") +
    `]);\n`;
  emit(join(apiGenerated, "reservedNodes.ts"), source);
  emit(join(webGenerated, "reservedNodes.ts"), source);
}

// The API's public RPC: the same URL the web app's CSP allows for wallet writes, so changing the
// endpoint in web/lib/endpoints.json can't leave the two disagreeing. A keyed (secret) fallback
// stays in the API's environment and never reaches this file or the browser.
{
  const endpoints = JSON.parse(readFileSync(join(repo, "web", "lib", "endpoints.json"), "utf8"));
  const url = endpoints?.evmRpc?.baseSepolia;
  if (typeof url !== "string" || !url.startsWith("https://")) {
    console.error("web/lib/endpoints.json: evmRpc.baseSepolia must be an https URL");
    process.exit(1);
  }
  emit(
    join(apiGenerated, "endpoints.ts"),
    header("web/lib/endpoints.json") + `export const BASE_SEPOLIA_PUBLIC_RPC = ${JSON.stringify(url)};\n`,
  );
}

// Verbatim copies for the web app: one definition of the deployment and of the record encoding,
// so the app (which encodes) and the API (which decodes) can't disagree.
for (const name of ["deployment.ts", "codec.ts", "names.ts"]) {
  const body = readFileSync(join(onchain, name), "utf8").replace(/\r\n/g, "\n");
  emit(join(webGenerated, name), header(`src/onchain/${name}`) + body);
}

if (stale) process.exit(1);
if (check) console.log("generated files up to date");
