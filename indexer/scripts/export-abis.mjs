// Generates abis/*.ts from the Foundry build output in ../contracts/out, plus
// abis/reservedNodes.ts from the hard-coded hashes in PaytagRegistry.isReserved.
//   node scripts/export-abis.mjs          write the files
//   node scripts/export-abis.mjs --check  exit 1 if the committed files are stale
// Run `forge build` in contracts/ first. The ABI is frozen at tag v0.1.0-contracts, so --check
// failing in CI means the contracts changed without the indexer being regenerated.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256, stringToBytes } from "viem";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = ["PaytagRegistry", "PaytagResolver"];
const check = process.argv.includes("--check");

let stale = false;
for (const name of contracts) {
  const artifact = join(root, "..", "contracts", "out", `${name}.sol`, `${name}.json`);
  if (!existsSync(artifact)) {
    console.error(`missing ${artifact}; run \`forge build\` in contracts/ first`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
  const source =
    `// Generated by scripts/export-abis.mjs from contracts/out/${name}.sol. Do not edit.\n` +
    `export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  const target = join(root, "abis", `${name}Abi.ts`);

  if (check) {
    const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== source) {
      console.error(`stale: abis/${name}Abi.ts (run \`npm run abis\`)`);
      stale = true;
    }
  } else {
    writeFileSync(target, source);
    console.log(`wrote abis/${name}Abi.ts`);
  }
}
// The reserved list is a pure function baked into the immutable registry, so the indexer answers
// it locally instead of making an RPC call per request.
{
  const sol = readFileSync(join(root, "..", "contracts", "src", "PaytagRegistry.sol"), "utf8");
  const entries = [...sol.matchAll(/node == (0x[0-9a-fA-F]{64})\s*\/\/\s*([a-z0-9_]+)/g)].map((m) => [
    m[2],
    m[1].toLowerCase(),
  ]);
  // Every hash in the contract must be extracted (none silently dropped for a missing or
  // malformed `// name` comment), and every comment must name the string that hashes to it.
  const allHashes = sol.match(/node == 0x[0-9a-fA-F]{64}/g) ?? [];
  if (entries.length === 0 || entries.length !== allHashes.length) {
    console.error(
      `reserved list: extracted ${entries.length} of ${allHashes.length} hashes; ` +
        "every `node == 0x…` in isReserved needs a trailing `// name` comment",
    );
    process.exit(1);
  }
  for (const [name, hash] of entries) {
    if (keccak256(stringToBytes(name)) !== hash) {
      console.error(`reserved list: comment "${name}" does not match hash ${hash}`);
      process.exit(1);
    }
  }
  const source =
    `// Generated by scripts/export-abis.mjs from PaytagRegistry.isReserved. Do not edit.\n` +
    `export const RESERVED_NODES: ReadonlySet<string> = new Set([\n` +
    entries.map(([name, hash]) => `  "${hash}", // ${name}\n`).join("") +
    `]);\n`;
  const target = join(root, "abis", "reservedNodes.ts");
  if (check) {
    const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== source) {
      console.error("stale: abis/reservedNodes.ts (run `npm run abis`)");
      stale = true;
    }
  } else {
    writeFileSync(target, source);
    console.log(`wrote abis/reservedNodes.ts (${entries.length} names)`);
  }
}

if (stale) process.exit(1);
if (check) console.log("abis up to date");
